import { createC2pa, Reader } from '@contentauth/c2pa-web/inline';

export interface C2paInspectionResult {
  status: 'detected' | 'no_credentials' | 'validation_failure' | 'inspection_error';
  title: string;
  summary: string;
  technicalDetails: string;
  manifestInfo?: {
    claimGenerator?: string;
    format?: string;
    title?: string;
    issuer?: string;
    signatureDate?: string;
    isSignatureValid?: boolean;
    validationErrors?: string[];
  };
}

let c2paPromise: Promise<any> | null = null;

/**
 * Initializes C2PA Web SDK singleton using the inline worker
 */
async function getC2paInstance() {
  if (!c2paPromise) {
    c2paPromise = createC2pa().catch((err) => {
      c2paPromise = null;
      throw err;
    });
  }
  return c2paPromise;
}

/**
 * Inspects a File or Blob for embedded C2PA Content Credentials
 */
export async function inspectC2paManifest(
  file: File | Blob
): Promise<C2paInspectionResult> {
  try {
    const c2pa = await getC2paInstance();
    const reader = await Reader.fromBlob(c2pa, file.type, file);

    if (!reader) {
      return {
        status: 'no_credentials',
        title: 'C2PA Content Credentials',
        summary: 'No C2PA manifest or JUMBF container found in file.',
        technicalDetails:
          'No embedded C2PA (Coalition for Content Provenance and Authenticity) manifest detected. Standard media without cryptographic provenance.',
      };
    }

    try {
      const activeManifest = await reader.activeManifest();

      if (!activeManifest) {
        return {
          status: 'no_credentials',
          title: 'C2PA Content Credentials',
          summary: 'C2PA store present but no active manifest found.',
          technicalDetails:
            'A JUMBF box structure exists, but does not contain an active claim manifest.',
        };
      }

      const manifest = activeManifest as any;
      const signatureInfo = manifest.signatureInfo || manifest.signature_info;
      const isSignatureValid = Boolean(signatureInfo?.issuer);
      const issuer = String(signatureInfo?.issuer || 'Unknown Signer');
      const claimGenerator = String(manifest.claimGenerator || manifest.claim_generator || 'Unknown Tool');
      const manifestTitle = manifest.title ? String(manifest.title) : undefined;
      const manifestFormat = manifest.format ? String(manifest.format) : undefined;

      return {
        status: 'detected',
        title: 'C2PA Content Credentials',
        summary: `Verified Content Credentials present (Issuer: ${issuer}).`,
        technicalDetails: `Active manifest: "${manifestTitle || 'Untitled'}" generated by ${claimGenerator}. Cryptographic signature detected.`,
        manifestInfo: {
          claimGenerator,
          format: manifestFormat,
          title: manifestTitle,
          issuer,
          isSignatureValid,
        },
      };
    } finally {
      await reader.free();
    }
  } catch (err: any) {
    const message = err?.message || String(err);
    // Check if error represents validation failure or no manifest
    if (
      message.includes('No JUMBF') ||
      message.includes('No claim') ||
      message.includes('not found') ||
      message.includes('Worker is not defined')
    ) {
      return {
        status: 'no_credentials',
        title: 'C2PA Content Credentials',
        summary: 'No embedded C2PA credentials detected in file headers.',
        technicalDetails:
          'The file stream contains no JUMBF container boxes or Content Credentials manifests.',
      };
    }

    if (message.includes('Validation') || message.includes('tampered') || message.includes('hash')) {
      return {
        status: 'validation_failure',
        title: 'C2PA Content Credentials',
        summary: 'C2PA credential validation failure: signature or hash mismatch.',
        technicalDetails: `A C2PA container was found, but failed verification: ${message}`,
      };
    }

    return {
      status: 'inspection_error',
      title: 'C2PA Content Credentials',
      summary: 'C2PA inspection encountered an issue.',
      technicalDetails: `C2PA reader returned: ${message}. Standard EXIF inspection remains active.`,
    };
  }
}
